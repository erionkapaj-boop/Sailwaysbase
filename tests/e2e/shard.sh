#!/usr/bin/env bash
# Μοιράζει τα αρχεία τεστ περιήγησης σε N κομμάτια για το CI (κάθε κομμάτι τρέχει
# σε δικό του μηχάνημα, με δική του βάση και δικές του θύρες).
#   bash tests/e2e/shard.sh <κομμάτι 1..N> <N>     → λίστα αρχείων του κομματιού
# Κυκλική μοιρασιά πάνω στη αλφαβητική λίστα, ώστε τα βαριά αρχεία να μη μαζεύονται
# στο ίδιο κομμάτι. Ένωση όλων των κομματιών = όλα τα αρχεία, χωρίς επικάλυψη.
set -euo pipefail
cd "$(dirname "$0")"
shard="${1:?κομμάτι}"; total="${2:?πλήθος}"
i=0
for f in *.e2e.mjs; do
  if [ $(( i % total )) -eq $(( shard - 1 )) ]; then printf '%s ' "$f"; fi
  i=$(( i + 1 ))
done
echo
