-- Πραγματικό, προϋπάρχον bug (όχι κάτι που άλλαξε η μεταφορά σκάφους): το
-- 0065 πρόσθεσε 4η παράμετρο (p_crew_role) στο net_availability με
-- "create or replace", χωρίς να πέσει πρώτα η παλιά 3-παράμετρη εκδοχή
-- (0049) — άρα τώρα υπάρχουν ΔΥΟ net_availability στη βάση, με όλες τις
-- επιπλέον παραμέτρους προαιρετικές. Οποιαδήποτε κλήση με λιγότερα
-- ορίσματα (π.χ. has_future_availability(p_skipper_id), μία μόνο
-- παράμετρος) είναι πλέον διφορούμενη — η Postgres δεν ξέρει ποια εκδοχή
-- εννοείς και σηκώνει "function net_availability(uuid) is not unique".
--
-- Το has_future_availability αποφασίζει το ✓/✗ "Διαθεσιμότητα" στο
-- checklist ορατότητας προφίλ (ProfileForm.js) — αλλά το app code
-- (hasFutureAvailability στο db.js) καταπίνει σιωπηλά κάθε σφάλμα RPC και
-- γυρίζει false, οπότε το checklist έδειχνε πάντα ✗ ασχέτως αν υπήρχε
-- πραγματικά δηλωμένη μελλοντική διαθεσιμότητα.
--
-- Η λύση είναι απλή: η 4-παράμετρη εκδοχή (0065) συμπεριφέρεται ήδη
-- ακριβώς όπως η 3-παράμετρη όταν p_crew_role είναι null (προεπιλογή) —
-- απλώς διαγράφεται η περιττή, παλιά εκδοχή.
--
-- Το ίδιο πρόβλημα χτυπούσε και κλήσεις με 2 ορίσματα — π.χ. τον έλεγχο
-- κάλυψης στο admin console (0024) — άρα πιθανώς επηρέαζε και τους
-- μετρητές "profiles_invisible" / "χρειάζονται κάλυψη" εκεί, όχι μόνο το
-- προφίλ.
--
-- Επιβεβαιωμένο τοπικά: πριν τη διαγραφή οι κλήσεις με 1 ή 2 ορίσματα
-- πετούσαν ambiguity error· μετά δουλεύουν σωστά, και το has_future_
-- availability γυρίζει true όταν υπάρχει πραγματικό μελλοντικό διάστημα
-- δηλωμένο.
--
-- Idempotent — ασφαλές να τρέξει ξανά.
-- ============================================================================
drop function if exists net_availability(uuid, uuid, uuid);
