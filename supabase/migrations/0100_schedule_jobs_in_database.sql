-- ============================================================================
-- Οι χρονικές προθεσμίες εκτελούνται μέσα στη βάση, κάθε 10 λεπτά.
--
-- Μέχρι τώρα η λήξη αιτημάτων και προτάσεων έτρεχε μόνο από το Vercel cron,
-- μία φορά τη νύχτα (03:00). Οι ενέργειες ήταν ήδη κλειδωμένες τη σωστή
-- στιγμή (κανείς δεν αποδέχεται ληγμένο αίτημα, ο πελάτης δεν διαλέγει μετά
-- τις 24 ώρες), αλλά ό,τι ακολουθεί τη λήξη περίμενε ως και ένα εικοσιτετράωρο:
--   - η επιστροφή χρημάτων στον πελάτη για αίτημα που δεν το πήρε κανείς
--   - η ειδοποίηση του πελάτη ότι έληξε
--   - το κλείσιμο πρότασης αντικατάστασης όταν ο πελάτης δεν διάλεξε ή δεν
--     απάντησε κανείς, με ειδοποίηση στον admin να ψάξει ξανά — για ταξίδι
--     που μπορεί να είναι σε δύο μέρες
--   - η ενημέρωση των υποψηφίων ότι η πρόταση έκλεισε
--   - το ίδιο για τις μεταφορές σκαφών
--
-- Το pg_cron υπάρχει σε κάθε έργο Supabase. Οι εργασίες τρέχουν ως ο
-- κάτοχος της βάσης, χωρίς συνδεδεμένο χρήστη, όπως το Vercel cron. Το
-- Vercel cron μένει ως εφεδρεία: οι συναρτήσεις είναι ασφαλείς να τρέξουν
-- ξανά (κλειδώνουν τις γραμμές και προσπερνούν ό,τι έχει ήδη κλείσει).
--
-- Όπου το pg_cron δεν είναι διαθέσιμο (π.χ. στη βάση των τεστ) δεν κάνει
-- τίποτα.
-- ============================================================================
do $$
begin
  -- Το pg_cron δουλεύει μόνο στη βάση που ορίζει το cron.database_name
  -- (στο Supabase: postgres).
  if not exists (select 1 from pg_available_extensions where name = 'pg_cron')
     or current_setting('cron.database_name', true) is distinct from current_database() then
    raise notice 'pg_cron not available in this database — jobs not scheduled';
    return;
  end if;
  create extension if not exists pg_cron;

  -- Ίδιο όνομα = αντικατάσταση της εργασίας, οπότε ασφαλές να ξανατρέξει.
  perform cron.schedule('platform-expire-deadlines', '*/10 * * * *',
    'select public.expire_stale_booking_requests()');
  perform cron.schedule('platform-complete-bookings', '5 * * * *',
    'select public.mark_bookings_completed()');
end;
$$;
