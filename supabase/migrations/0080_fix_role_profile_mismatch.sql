-- ============================================================================
-- Βρέθηκε (αναφορά χρήστη): ο δοκιμαστικός λογαριασμός «Εριόν» έβγαζε
-- φωτογραφία κανονικά στην αναζήτηση, αλλά καμία φωτογραφία στη δική του
-- σελίδα προφίλ μετά από «Σύνδεση ως». Αιτία: users.role = 'client' ενώ
-- υπήρχε ήδη εγκεκριμένο skipper_profiles με πραγματική φωτογραφία — η
-- σελίδα προφίλ (και το AuthContext) αποφασίζουν ΠΟΙΑ φόρμα/προφίλ να
-- φορτώσουν αποκλειστικά με βάση το users.role, όχι με βάση το αν όντως
-- υπάρχει εγκεκριμένο επαγγελματικό προφίλ — οπότε έδειχναν τη φόρμα πελάτη
-- (users.photo_url, κενό) σε κάποιον με πλήρες επαγγελματικό προφίλ.
--
-- Προέλευση: το 0062 (κυκλική κατανομή δοκιμαστικών λογαριασμών σε ρόλους)
-- είχε φτιάξει/εγκρίνει skipper_profiles για κάποιους δοκιμαστικούς
-- λογαριασμούς· αργότερα ξαναγύρισαν σε role='client' (είτε από νέο πέρασμα
-- του ίδιου κυκλικού migration, είτε από το 0076 που επανέφερε τους
-- κυκλικά-ανατεθειμένους 'admin' σε 'client') χωρίς να καθαριστεί το ήδη
-- υπάρχον skipper_profiles τους. Αποτέλεσμα: λογαριασμός με δύο
-- αντικρουόμενες ταυτότητες ταυτόχρονα.
--
-- Διόρθωση: μόνο για is_test_account = true (ο μόνος τρόπος να προέκυψε
-- αυτό στην πράξη — 0062/0076 αφορούσαν αποκλειστικά δοκιμαστικούς
-- λογαριασμούς) — αν υπάρχει εγκεκριμένο, μη-διαγραμμένο skipper_profiles
-- αλλά users.role δεν είναι ήδη 'skipper' (ούτε 'admin', που ήδη καλύπτεται
-- σωστά παντού), το users.role συμφωνεί με αυτό που όντως ισχύει.
--
-- Idempotent — ασφαλές να τρέξει ξανά.
-- ============================================================================

update users u
set role = 'skipper'
where u.is_test_account = true
  and u.role = 'client'
  and exists (
    select 1 from skipper_profiles sp
    where sp.user_id = u.id and sp.deleted_at is null and sp.approval_status = 'approved'
  );
