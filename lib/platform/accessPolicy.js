// ΚΕΝΤΡΙΚΟ σημείο «απαιτείται σύνδεση» (εντολή ιδιοκτήτη 17/10/2026).
//
// Προς το παρόν οι εφαρμογές (Jobs, Delivery, WindNow, Nearby, Explore, Community) ανοίγουν και χρησιμοποιούνται χωρίς
// σύνδεση, και πουθενά δεν εμφανίζεται αίτημα σύνδεσης (δεν υπάρχουν ακόμα χρήστες). Ο παλιός κώδικας ελέγχου σύνδεσης και
// δικαιωμάτων ΔΕΝ αφαιρέθηκε: κάθε σημείο που σταματούσε τον επισκέπτη ρωτά πλέον εδώ αν η συγκεκριμένη ενέργεια
// θέλει σύνδεση. Για να ξαναζητηθεί σύνδεση σε μια ενέργεια, προσθέτεις το κλειδί της στο LOGIN_REQUIRED — τίποτα άλλο.
//
// Κλειδιά (ό,τι έχει συνδεθεί με αυτό το αρχείο):
//   board_claim        διεκδίκηση αιτήματος στον πίνακα Jobs / Nearby
//   board_new          ανάρτηση ανοιχτού αιτήματος (Jobs)
//   delivery_send      αποστολή αιτήματος μεταφοράς σκάφους (Delivery)
//   delivery_requests  τα αιτήματα μεταφοράς μου (Delivery)
//   community          η Community συνολικά (χάρτης και ομάδες)
//   community_write    προσθήκη/διόρθωση σημείου, αναφορά, συμμετοχή σε ομάδα, μήνυμα
//
// Ενέργειες που στην πράξη ΔΕΝ δουλεύουν χωρίς χρήστη (η βάση χρειάζεται συντάκτη/πορτοφόλι/προφίλ): η διεκδίκηση και η
// ανάρτηση αιτήματος, η αποστολή μεταφοράς, και όλες οι εγγραφές της Community. Ο επισκέπτης τις δοκιμάζει και παίρνει το
// ουδέτερο μήνυμα «Η ενέργεια χρειάζεται λογαριασμό» (accountNeededMessage) — όχι αίτημα σύνδεσης.
import { tNow } from "./tNow";

export const LOGIN_REQUIRED = new Set([]);

export function requiresLogin(action) {
  return LOGIN_REQUIRED.has(action);
}

// Πρέπει να εμφανιστεί η προηγούμενη συμπεριφορά «σύνδεση πρώτα» (σελίδα σύνδεσης, ειδοποίηση, κουμπί Σύνδεση);
export function loginWall(session, action) {
  return !session && requiresLogin(action);
}

// Για ενέργεια που ο επισκέπτης επιτρέπεται να δοκιμάσει αλλά δεν μπορεί να ολοκληρωθεί χωρίς λογαριασμό.
export function accountNeededMessage() {
  return tNow("Errors", "accountNeeded");
}
